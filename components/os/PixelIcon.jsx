export default function PixelIcon({ name, size = 24 }) {
  const rows = BITMAPS[name] || BITMAPS.projects;
  const d = rows
    .flatMap((row, y) => [...row].map((c, x) => (c === "#" ? `M${x} ${y}h1v1h-1z` : "")))
    .join("");
  return (
    <svg width={size} height={size} viewBox="0 0 12 12" shapeRendering="crispEdges" aria-hidden="true" focusable="false">
      <path d={d} fill="currentColor" />
    </svg>
  );
}
